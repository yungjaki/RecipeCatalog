    /// <summary>Попълва празна база с начални данни. Не прави нищо, ако вече има рецепти.</summary>
    public static void SeedIfEmpty(IRecipeRepository repository)
    {
        if (repository.CountRecipes() > 0)
        {
            return;
        }

        var categoryIds = EnsureCategories(repository);
        foreach (var seed in Recipes)
        {
            var id = repository.Add(ToInput(seed, categoryIds));
            foreach (var stars in seed.Ratings)
            {
                repository.AddRating(id, stars);
            }
        }
    }

    private static List<int> EnsureCategories(IRecipeRepository repository)
    {
        var existing = repository.GetCategories();
        return Categories
            .Select(name => existing.FirstOrDefault(c => c.Name == name)?.Id ?? repository.AddCategory(name))
            .ToList();
    }

    private static RecipeInput ToInput(SeedRecipe seed, IReadOnlyList<int> categoryIds) => new()
    {
        Name = seed.Name,
        CategoryId = categoryIds[seed.Category],
        PrepTimeMinutes = seed.Minutes,
        ImagePath = $"/images/recipes/{seed.Image}.svg",
        Instructions = seed.Instructions,
        Ingredients = IngredientLineParser.Parse(seed.Ingredients)
    };
